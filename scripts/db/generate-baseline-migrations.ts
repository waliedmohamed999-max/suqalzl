/**
 * Builds the BASELINE migrations (0001–0010) from prisma/schema.prisma + hand-written SQL.
 *
 * Why: the Prisma schema-engine binary (needed by `prisma migrate dev/diff`) cannot be downloaded
 * in the build sandbox (binaries.prisma.sh → 403, same as P1-00). This script turns the Prisma DMMF
 * into DDL using Prisma's own naming conventions (`_pkey`, `_key`, `_idx`, `_fkey`, RESTRICT/SET NULL,
 * ON UPDATE CASCADE), so the folders are standard Prisma migrations: `prisma migrate deploy` applies
 * them as-is on CI and on any machine.
 *
 * For each migration NNNN_name:
 *   prisma/migrations/NNNN_name/migration.sql = prisma/sql/NNNN_name.pre.sql (sequences, ...)
 *                                              + generated DDL for its models
 *                                              + prisma/sql/NNNN_name.sql (RLS, CHECKs, triggers, ...)
 *
 * RULE: only for the baseline, BEFORE any environment has applied it. Once a migration is applied
 * anywhere it is immutable; later changes = new migrations (`prisma migrate dev` where engines exist).
 * tests/db/schema-drift.test.ts checks the applied database against the DMMF.
 *
 * Usage: npx tsx scripts/db/generate-baseline-migrations.ts
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import internals from "@prisma/internals";
import { MIGRATION_PLAN } from "./migration-plan";
import { buildDdl } from "./ddl";

const { getDMMF } = internals;
const root = path.resolve(import.meta.dirname, "../..");

async function main() {
  const datamodel = readFileSync(path.join(root, "prisma/schema.prisma"), "utf8");
  const dmmf = await getDMMF({ datamodel });

  const planned = MIGRATION_PLAN.flatMap((m) => m.models);
  const all = dmmf.datamodel.models.map((m) => m.name);
  const missing = all.filter((m) => !planned.includes(m));
  const unknown = planned.filter((m) => !all.includes(m));
  if (missing.length || unknown.length) {
    throw new Error(`migration plan mismatch. not planned: [${missing}] unknown: [${unknown}]`);
  }

  const created = new Set<string>();
  const createdEnums = new Set<string>();
  for (const step of MIGRATION_PLAN) {
    const ddl = buildDdl(dmmf.datamodel, step.models, created, createdEnums);
    const extraPath = path.join(root, "prisma/sql", `${step.name}.sql`);
    const extra = existsSync(extraPath) ? readFileSync(extraPath, "utf8") : "";
    const prePath = path.join(root, "prisma/sql", `${step.name}.pre.sql`);
    const pre = existsSync(prePath) ? readFileSync(prePath, "utf8") : "";
    const out = [
      `-- ${step.name}`,
      `-- ${step.description}`,
      "-- Part 1 is generated from prisma/schema.prisma by scripts/db/generate-baseline-migrations.ts.",
      `-- Part 2 is hand-written: prisma/sql/${step.name}.sql`,
      "",
      ...(pre
        ? [
            "-- ======================================================================= part 0: hand-written (before tables)",
            pre.trim(),
            "",
          ]
        : []),
      "-- ======================================================================= part 1: tables",
      ddl.trim(),
      "",
      "-- ======================================================================= part 2: hand-written",
      extra.trim(),
      "",
    ].join("\n");
    const dir = path.join(root, "prisma/migrations", step.name);
    mkdirSync(dir, { recursive: true });
    writeFileSync(path.join(dir, "migration.sql"), out);
    console.log(`wrote ${step.name} (${step.models.length} models)`);
  }
  writeFileSync(
    path.join(root, "prisma/migrations/migration_lock.toml"),
    '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
